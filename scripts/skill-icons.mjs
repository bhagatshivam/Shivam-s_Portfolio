// Regenerates src/data/skillIconPaths.js: the SVG path of each skill logo, copied from the
// simple-icons devDependency so the site bundles them at build time (no CDN, no runtime
// dependency). Run after adding a skill:  node scripts/skill-icons.mjs
// Skills with no entry here (LangGraph, FAISS, BGE, Qwen, pdf.js...) get a monogram instead.
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const wanted = {
  python: "siPython",
  typescript: "siTypescript",
  javascript: "siJavascript",
  c: "siC",
  cpp: "siCplusplus",
  html5: "siHtml5",
  mysql: "siMysql",
  mongodb: "siMongodb",
  vercel: "siVercel",
  react: "siReact",
  vite: "siVite",
  tailwind: "siTailwindcss",
  shadcn: "siShadcnui",
  nextjs: "siNextdotjs",
  streamlit: "siStreamlit",
  supabase: "siSupabase",
  postgresql: "siPostgresql",
  nodejs: "siNodedotjs",
  pandas: "siPandas",
  numpy: "siNumpy",
  transformers: "siHuggingface",
  gemini: "siGooglegemini",
  pytorch: "siPytorch",
  sklearn: "siScikitlearn",
  opencv: "siOpencv",
  "github-actions": "siGithubactions",
  yaml: "siYaml",
  mermaid: "siMermaid",
  vitest: "siVitest",
  git: "siGit",
  docker: "siDocker",
  linux: "siLinux",
  capacitor: "siCapacitor",
  "android-saf": "siAndroid",
};

const out = {};
for (const [id, key] of Object.entries(wanted)) {
  if (!si[key]) throw new Error(`simple-icons has no ${key}`);
  out[id] = si[key].path;
}
const body = Object.entries(out)
  .map(([id, d]) => `  ${JSON.stringify(id)}: ${JSON.stringify(d)},`)
  .join("\n");
writeFileSync(
  new URL("../src/data/skillIconPaths.js", import.meta.url),
  `// Generated by scripts/skill-icons.mjs from simple-icons (CC0). Do not edit by hand.\n// Each value is the path of a 24x24 SVG; render with fill="currentColor".\nexport const skillIconPaths = {\n${body}\n};\n`
);
console.log(`wrote ${Object.keys(out).length} icons`);
